#!/usr/bin/env python3
"""Create a public-only Pages artifact, asset hashes and sharing metadata."""
from pathlib import Path
import hashlib, html, json, re, shutil
from prepare_photos import IMAGE_EXTS, embedded_metadata, sanitize_media_bytes, sanitize_metadata

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / '_site'
ORIGIN = 'https://love.itestv.com'

def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]

def build():
    if OUT.exists():
        if not (OUT / '.build-output').exists():
            raise RuntimeError('Refusing to replace an unrecognised _site directory')
        shutil.rmtree(OUT)
    OUT.mkdir()
    (OUT / '.build-output').write_text('Generated by scripts/build_site.py\n')
    for name in ('index.html','photo.html','photo-detail.html','notes.html','note.html','movie.html','music.html','timeline.html','404.html','offline.html','manifest.json','robots.txt','CNAME'):
        source = ROOT / name
        if source.exists():
            shutil.copy2(source, OUT / name)
    for folder in ('css','js','fonts','icons','generated'):
        source = ROOT / 'assets' / folder
        if source.exists():
            if folder in ('css','js'):
                names = ('tokens.css','base.css','home.css','photo.css','archive.css','notes.css','utility.css') if folder == 'css' else ('theme.js','home.js','gallery.js','archive.js','notes.js','timeline.js','photo-redirect.js','photo-data.json')
                for name in names:
                    if (source / name).exists():
                        dest = OUT / 'assets' / folder / name
                        dest.parent.mkdir(parents=True, exist_ok=True)
                        shutil.copy2(source / name, dest)
            else:
                shutil.copytree(source, OUT / 'assets' / folder)
    for name in ('share-card.png','brand-mark.svg'):
        if (ROOT / 'assets' / name).exists():
            shutil.copy2(ROOT / 'assets' / name, OUT / 'assets' / name)
    for folder in ('data','music','images'):
        if (ROOT / folder).exists():
            shutil.copytree(ROOT / folder, OUT / folder)
    for name in ('baby.png','love.png'):
        if (ROOT / name).exists():
            shutil.copy2(ROOT / name, OUT / name)
    for source in (ROOT / 'blog' / 'rendered').glob('*.html'):
        dest = OUT / 'blog' / 'rendered' / source.name
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, dest)
    (OUT / 'blog').mkdir(exist_ok=True)
    shutil.copy2(ROOT / 'blog' / 'posts.json', OUT / 'blog' / 'posts.json')
    if (ROOT / 'blog' / 'images').exists():
        for source in (ROOT / 'blog' / 'images').rglob('*'):
            if source.is_file() and source.suffix.lower() in IMAGE_EXTS:
                target = OUT / source.relative_to(ROOT)
                target.parent.mkdir(parents=True, exist_ok=True)
                metadata = sanitize_metadata(embedded_metadata(source))
                target.write_bytes(sanitize_media_bytes(source, metadata))
    data_path = OUT / 'assets' / 'js' / 'photo-data.json'
    photos = json.loads(data_path.read_text())
    # Preserve older public /photo/ URLs using sanitized generated copies only.
    for photo in photos:
        source = (ROOT / photo['full']).resolve()
        if not source.is_relative_to(ROOT / 'assets' / 'generated'):
            raise RuntimeError('Public photo must point at privacy-prepared output')
        name = Path(photo['file']).name
        target = OUT / 'photo' / name
        target.parent.mkdir(exist_ok=True)
        shutil.copy2(source, target)
    hashed_name = f'photo-data.{digest(data_path)}.json'
    shutil.copy2(data_path, data_path.with_name(hashed_name))
    for path in (OUT / 'assets' / 'js').glob('*.js'):
        text = path.read_text()
        text = text.replace('assets/js/photo-data.json', 'assets/js/' + hashed_name)
        path.write_text(text)
    descriptions = {
        'index.html':'把共同走过的时间、风景与舍不得忘的瞬间，留在一册可以慢慢重看的记忆里。',
        'photo.html':'Tankey 与 Monody 的光影记录，每一张照片都是留给未来的此刻。',
        'notes.html':'生活、喜爱与共同成长的手记。', 'note.html':'从日常里留下来的片刻，慢慢读，慢慢记。',
        'movie.html':'一起看过和想看的电影，留住银幕另一边的故事。', 'music.html':'把声音留给时间，收藏那些有温度的旋律。',
        'timeline.html':'照片与手记串起共同走过的时光。', '404.html':'这一页暂时不在这里，回到我们的记忆里。', 'offline.html':'暂时离线，已经看过的记忆仍可以慢慢重看。'
    }
    for page in OUT.glob('*.html'):
        text = page.read_text()
        text = re.sub(r'<meta\s+(?:name|property)=["\'](?:description|theme-color|robots|og:[^"\']+|twitter:[^"\']+)["\'][^>]*>', '', text, flags=re.I)
        text = re.sub(r'<link[^>]+rel=["\'](?:icon|apple-touch-icon|manifest|canonical)["\'][^>]*>', '', text, flags=re.I)
        title = re.search(r'<title>(.*?)</title>', text, re.S)
        title = html.unescape(title.group(1)) if title else 'Tankey & Monody'
        description = descriptions.get(page.name, descriptions['index.html'])
        meta = f'''<meta name="description" content="{html.escape(description, quote=True)}">
<meta name="robots" content="noindex, nofollow, noarchive">
<meta name="theme-color" content="#edf3f4" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#1d1f1c" media="(prefers-color-scheme: dark)">
<meta property="og:type" content="website"><meta property="og:locale" content="zh_CN">
<meta property="og:title" content="{html.escape(title, quote=True)}"><meta property="og:description" content="{html.escape(description, quote=True)}">
<meta property="og:url" content="{ORIGIN}/{page.name}"><meta property="og:image" content="{ORIGIN}/assets/share-card.png">
<meta property="og:image:width" content="1200"><meta property="og:image:height" content="630"><meta property="og:image:alt" content="Tankey 与 Monody 的纪念册">
<meta name="twitter:card" content="summary_large_image"><link rel="canonical" href="{ORIGIN}/{page.name}">
<link rel="icon" href="assets/brand-mark.svg" type="image/svg+xml"><link rel="apple-touch-icon" href="assets/icons/apple-touch-icon.png"><link rel="manifest" href="manifest.json">
'''
        text = text.replace('</head>', meta + '</head>')
        def version(match):
            path = match.group(2).split('?')[0]
            file = OUT / path
            if not file.is_file() or file.suffix not in ('.css','.js'):
                return match.group(0)
            return match.group(1) + path + '?v=' + digest(file) + match.group(3)
        text = re.sub(r'((?:src|href)=["\'])(assets/[^"\']+)(["\'])', version, text)
        page.write_text(text)
    version = hashlib.sha256(''.join(digest(p) for p in sorted(OUT.rglob('*')) if p.is_file()).encode()).hexdigest()[:12]
    precache = ['offline.html', 'index.html', 'assets/icons/icon-192.png']
    precache += [path.relative_to(OUT).as_posix() for folder in ('css','js','fonts') for path in sorted((OUT / 'assets' / folder).rglob('*')) if path.is_file() and path.suffix in ('.css','.js','.woff2','.json')]
    worker = (ROOT / 'sw.js').read_text().replace('__BUILD_VERSION__', version).replace('__PRECACHE__', json.dumps(precache))
    (OUT / 'sw.js').write_text(worker)
    (OUT / '.nojekyll').touch()
    print(f'Public artifact: {OUT}; {len(photos)} privacy-prepared photos; build {version}')

if __name__ == '__main__':
    build()
